"""
torch_dataset.py
-----------------
PyTorch Dataset that reads the SAME annotation format used by the NumPy
version (filename, class_id, class_name, has_animal, xmin, ymin, xmax, ymax).

This means you can point it at:
  - the synthetic dataset already generated by src/generate_dataset.py, OR
  - your own real-photo dataset, as long as you produce a CSV in this
    exact schema (see the bottom of this file for a helper that builds
    one from a folder of images + a simple labeling loop, or from a
    standard COCO-format export).

Requires: pip install torch torchvision  (not available in the sandbox
this was written in -- run this on your own machine).
"""

import os
import csv
import torch
from torch.utils.data import Dataset
from PIL import Image
import torchvision.transforms.functional as TF

CLASSES = ["dog", "cat", "bird", "rabbit"]  # extend this list for real datasets
CLASS_TO_ID = {c: i for i, c in enumerate(CLASSES)}


class AnimalDetectionDataset(Dataset):
    def __init__(self, split_dir, img_size=128):
        self.split_dir = split_dir
        self.img_size = img_size
        ann_path = os.path.join(split_dir, "annotations.csv")
        self.rows = list(csv.DictReader(open(ann_path)))

    def __len__(self):
        return len(self.rows)

    def __getitem__(self, idx):
        r = self.rows[idx]
        img_path = os.path.join(self.split_dir, "images", r["filename"])
        img = Image.open(img_path).convert("RGB")
        ow, oh = img.size
        img = img.resize((self.img_size, self.img_size))
        x = TF.to_tensor(img)  # (3,H,W) in [0,1]

        has_animal = float(r["has_animal"])
        if has_animal:
            xmin = float(r["xmin"]) / ow
            ymin = float(r["ymin"]) / oh
            xmax = float(r["xmax"]) / ow
            ymax = float(r["ymax"]) / oh
            class_id = int(r["class_id"])
        else:
            xmin = ymin = xmax = ymax = 0.0
            class_id = -1  # ignored when has_animal == 0

        target = {
            "objectness": torch.tensor(has_animal, dtype=torch.float32),
            "box": torch.tensor([xmin, ymin, xmax, ymax], dtype=torch.float32),
            "class_id": torch.tensor(max(class_id, 0), dtype=torch.long),
            "has_animal": torch.tensor(has_animal, dtype=torch.float32),
        }
        return x, target


# ---------------------------------------------------------------------------
# Helper for building an annotations.csv for YOUR OWN real photos, if you
# want to fine-tune on real data instead of (or in addition to) the
# synthetic set. You will need to supply the box coordinates yourself
# (e.g. using a free tool like makesense.ai, LabelImg, or CVAT to draw
# boxes on your photos and export them), then convert to this schema.
# ---------------------------------------------------------------------------
def write_annotations_csv(out_csv_path, entries):
    """
    entries: list of dicts with keys
        filename, class_name, has_animal (0/1), xmin, ymin, xmax, ymax
    (xmin..ymax in absolute pixel coordinates of the saved image file)
    """
    with open(out_csv_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["filename", "class_id", "class_name", "has_animal", "xmin", "ymin", "xmax", "ymax"])
        for e in entries:
            class_id = CLASS_TO_ID.get(e["class_name"], -1)
            writer.writerow([e["filename"], class_id, e["class_name"], e["has_animal"],
                              e["xmin"], e["ymin"], e["xmax"], e["ymax"]])
